create or replace function public.create_league_workspace(p_name text default 'My League')
returns uuid language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_workspace uuid; v_name text:=left(trim(coalesce(p_name,'My League')),80);
begin
 if v_user is null then raise exception 'Sign in is required'; end if;
 if length(v_name)<2 then v_name:='My League'; end if;
 insert into public.league_workspaces(name,owner_id) values(v_name,v_user) returning id into v_workspace;
 insert into public.workspace_members(workspace_id,user_id,role) values(v_workspace,v_user,'owner');
 insert into public.league_policy_rules(workspace_id,rule_type,name,period_type,target_ap,duration_hours,minimum_ovr,enabled)
 values (v_workspace,'onboarding','New member onboarding','onboarding',500,2,null,true),
        (v_workspace,'activity_quota','Weekly AP quota','weekly',1500,null,null,true),
        (v_workspace,'ovr_threshold','Minimum OVR review','none',null,null,1,false);
 return v_workspace;
end;
$$;
revoke all on function public.create_league_workspace(text) from public,anon;
grant execute on function public.create_league_workspace(text) to authenticated;

create or replace function public.create_action_review_for_shortfall()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
 if new.alert_type in ('onboarding_shortfall','weekly_shortfall','monthly_shortfall','custom_shortfall','ovr_shortfall') and new.member_id is not null then
  insert into public.league_action_reviews(member_id,source_alert_id,workspace_id,reason)
   values(new.member_id,new.id,new.workspace_id,new.message) on conflict(source_alert_id) do nothing;
 end if;
 return new;
end;
$$;
drop trigger if exists league_shortfall_action_review on public.league_alerts;
create trigger league_shortfall_action_review after insert on public.league_alerts for each row execute function public.create_action_review_for_shortfall();
insert into public.league_action_reviews(member_id,source_alert_id,workspace_id,reason)
 select a.member_id,a.id,a.workspace_id,a.message from public.league_alerts a
 where a.alert_type in ('onboarding_shortfall','weekly_shortfall','monthly_shortfall','custom_shortfall','ovr_shortfall') and a.member_id is not null
 on conflict(source_alert_id) do nothing;

create or replace function public.review_league_action(p_action_id bigint,p_decision text)
returns void language plpgsql security definer set search_path=''
as $$
declare v_workspace uuid;
begin
 if p_decision is null or p_decision not in ('approve','decline') then raise exception 'Decision must be approve or decline'; end if;
 select workspace_id into v_workspace from public.league_action_reviews where id=p_action_id;
 if not found or not public.can_manage_workspace(v_workspace) then raise exception 'Workspace manager access required'; end if;
 update public.league_action_reviews set status=case when p_decision='approve' then 'approved' else 'declined' end,
  reviewed_at=now(),reviewed_by=auth.uid() where id=p_action_id and status='pending';
 if not found then raise exception 'Review item not found or no longer pending'; end if;
end;
$$;
create or replace function public.complete_league_action(p_action_id bigint,p_note text)
returns void language plpgsql security definer set search_path=''
as $$
declare v_member bigint; v_workspace uuid;
begin
 if nullif(trim(coalesce(p_note,'')),'') is null then raise exception 'A completion note is required'; end if;
 select member_id,workspace_id into v_member,v_workspace from public.league_action_reviews where id=p_action_id and status='approved';
 if not found or not public.can_manage_workspace(v_workspace) then raise exception 'Approved review and workspace manager access required'; end if;
 update public.league_action_reviews set status='completed',completed_at=now(),completed_by=auth.uid(),
  completion_note=left(trim(p_note),500) where id=p_action_id and status='approved';
 if not found then raise exception 'Action must be approved before completion'; end if;
 if v_member is not null then update public.league_members set status='removed' where id=v_member and workspace_id=v_workspace; end if;
end;
$$;
revoke all on function public.create_action_review_for_shortfall() from public,anon,authenticated;

do $$
declare v_owner uuid; v_workspace uuid;
begin
  select id into v_owner from auth.users where raw_app_meta_data->>'role'='league_admin' order by created_at asc limit 1;
  if v_owner is null then select id into v_owner from auth.users order by created_at asc limit 1; end if;
  if v_owner is null then raise exception 'Create a Supabase Auth user before applying this migration'; end if;
  select workspace_id into v_workspace from public.workspace_members where user_id=v_owner order by created_at asc limit 1;
  if v_workspace is null then
    insert into public.league_workspaces(name,owner_id) values('My League',v_owner) returning id into v_workspace;
    insert into public.workspace_members(workspace_id,user_id,role) values(v_workspace,v_owner,'owner');

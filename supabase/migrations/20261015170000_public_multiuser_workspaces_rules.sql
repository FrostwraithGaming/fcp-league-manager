-- Public, multi-workspace league manager: workspace membership, policies, and tenant RLS.
create table if not exists public.league_workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 2 and 80),
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.workspace_members (
  workspace_id uuid not null references public.league_workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','member')),
  created_at timestamptz not null default now(),
  primary key(workspace_id,user_id)
);
create table if not exists public.league_policy_rules (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.league_workspaces(id) on delete cascade,
  rule_type text not null check (rule_type in ('onboarding','activity_quota','ovr_threshold')),
  name text not null check (length(trim(name)) between 2 and 100),
  period_type text not null default 'none' check (period_type in ('none','onboarding','weekly','monthly','custom')),
  target_ap integer check (target_ap between 0 and 9999999),
  duration_hours integer check (duration_hours between 1 and 8760),
  minimum_ovr integer check (minimum_ovr between 1 and 999),
  enabled boolean not null default true,
  action_mode text not null default 'recommend_only' check (action_mode='recommend_only'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (rule_type='onboarding' and period_type='onboarding' and target_ap is not null and duration_hours is not null)
    or (rule_type='activity_quota' and period_type in ('weekly','monthly','custom') and target_ap is not null
        and (period_type<>'custom' or duration_hours is not null))
    or (rule_type='ovr_threshold' and period_type='none' and minimum_ovr is not null)
  )
);
create unique index if not exists league_policy_rules_one_onboarding
 on public.league_policy_rules(workspace_id) where rule_type='onboarding' and enabled;
create unique index if not exists league_policy_rules_quota_name
 on public.league_policy_rules(workspace_id,lower(name)) where rule_type='activity_quota';
create unique index if not exists league_policy_rules_ovr_name
 on public.league_policy_rules(workspace_id,lower(name)) where rule_type='ovr_threshold';
create index if not exists league_policy_rules_workspace_idx on public.league_policy_rules(workspace_id,enabled,rule_type);

create or replace function public.is_workspace_member(p_workspace_id uuid)
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.workspace_members wm where wm.workspace_id=p_workspace_id and wm.user_id=auth.uid()); $$;
create or replace function public.can_manage_workspace(p_workspace_id uuid)
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.workspace_members wm where wm.workspace_id=p_workspace_id and wm.user_id=auth.uid() and wm.role in ('owner','admin')); $$;
grant execute on function public.is_workspace_member(uuid) to authenticated;
grant execute on function public.can_manage_workspace(uuid) to authenticated;


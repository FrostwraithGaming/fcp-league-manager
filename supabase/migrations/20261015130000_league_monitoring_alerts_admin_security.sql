-- FCP League Manager 27 - monitoring and admin-security migration
-- Applied to project ekfziidavohcdzbypocn on 2026-10-15.
-- Keep public sign-ups disabled. Only trusted accounts should have app_metadata.role=league_admin.

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists public.league_alerts (
  id bigint generated by default as identity primary key,
  member_id bigint references public.league_members(id) on delete set null,
  alert_type text not null check (alert_type in ('onboarding_shortfall','weekly_shortfall','weekly_data_gap')),
  period_start timestamptz,
  fingerprint text not null unique,
  title text not null,
  message text not null,
  severity text not null default 'warning' check (severity in ('info','warning','critical')),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists league_alerts_created_at_idx on public.league_alerts(created_at desc);
create index if not exists activity_history_member_recorded_idx on public.activity_history(member_id, recorded_at desc, id desc);
create index if not exists league_members_status_deadline_idx on public.league_members(status, initial_deadline);

create or replace function public.is_league_admin()
returns boolean language sql stable security invoker set search_path = ''
as $$ select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'league_admin', false); $$;
grant execute on function public.is_league_admin() to authenticated;

alter table public.league_members enable row level security;
alter table public.activity_history enable row level security;
alter table public.league_settings enable row level security;
alter table public.league_alerts enable row level security;

drop policy if exists "Authenticated admins can manage league members" on public.league_members;
drop policy if exists "Authenticated admins can manage activity history" on public.activity_history;
drop policy if exists "Authenticated admins can read league settings" on public.league_settings;
drop policy if exists "Authenticated admins can update league settings" on public.league_settings;
drop policy if exists "League admins only manage members" on public.league_members;
drop policy if exists "League admins only manage history" on public.activity_history;
drop policy if exists "League admins only manage settings" on public.league_settings;
drop policy if exists "League admins only manage alerts" on public.league_alerts;

create policy "League admins only manage members" on public.league_members for all to authenticated
using (public.is_league_admin()) with check (public.is_league_admin());
create policy "League admins only manage history" on public.activity_history for all to authenticated
using (public.is_league_admin()) with check (public.is_league_admin());
create policy "League admins only manage settings" on public.league_settings for all to authenticated
using (public.is_league_admin()) with check (public.is_league_admin());
create policy "League admins only manage alerts" on public.league_alerts for all to authenticated
using (public.is_league_admin()) with check (public.is_league_admin());

grant select, insert, update, delete on public.league_members, public.activity_history, public.league_settings to authenticated;
grant select, update on public.league_alerts to authenticated;
grant usage, select on all sequences in schema public to authenticated;

update auth.users
set raw_app_meta_data = coalesce(raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('role', 'league_admin')
where id = (select id from auth.users order by created_at asc limit 1);

create or replace function public.monitor_league_activity()
returns jsonb language plpgsql security definer
set search_path = public, extensions, vault, pg_temp
as $$
declare
  v_now timestamptz := now();
  v_local timestamp := now() at time zone 'Asia/Kolkata';
  v_week_start timestamptz;
  v_target integer := 500;
  v_week_target integer := 1500;
  v_webhook text;
  v_alert_id bigint;
  v_onboarding_count integer := 0;
  v_weekly_count integer := 0;
  v_gap_count integer := 0;
  v_prev_points integer;
  v_week_points integer;
  v_baseline_at timestamptz;
  v_latest_at timestamptz;
  v_message text;
  v_payload jsonb;
  rec record;
  snap record;
begin
  v_week_start := date_trunc('week', v_local) at time zone 'Asia/Kolkata';
  select coalesce(initial_target,500), coalesce(weekly_target,1500)
    into v_target, v_week_target from public.league_settings where id=1;
  v_target := coalesce(v_target,500); v_week_target := coalesce(v_week_target,1500);

  update public.league_members set status='active'
    where status in ('pending','review')
      and greatest(coalesce(last_points,0)-coalesce(initial_points,0),0) >= v_target;

  for rec in
    select id, player_name, initial_deadline, initial_points, last_points
    from public.league_members where status in ('pending','review')
      and initial_deadline <= v_now
      and greatest(coalesce(last_points,0)-coalesce(initial_points,0),0) < v_target
  loop
    update public.league_members set status='review' where id=rec.id and status <> 'review';
    v_message := format('%s has not reached %s AP within the two-hour onboarding window. Current tracked gain: %s AP. Review the member before taking any in-game action.',
      left(replace(coalesce(rec.player_name,'Member'), '@', '@​'),100),
      v_target, greatest(coalesce(rec.last_points,0)-coalesce(rec.initial_points,0),0));
    insert into public.league_alerts(member_id,alert_type,period_start,fingerprint,title,message,severity)
    values(rec.id,'onboarding_shortfall',rec.initial_deadline,
      'onboarding_shortfall:'||rec.id::text||':'||rec.initial_deadline::text,
      'Onboarding target missed',v_message,'warning')
    on conflict(fingerprint) do nothing returning id into v_alert_id;
    if v_alert_id is not null then v_onboarding_count:=v_onboarding_count+1; v_alert_id:=null; end if;
  end loop;

  if extract(isodow from v_local)=7 and v_local::time >= time '20:00' then
    for rec in select id, player_name from public.league_members where status <> 'removed'
    loop
      v_prev_points:=null; v_week_points:=0; v_baseline_at:=null; v_latest_at:=null;
      select h.activity_points,h.recorded_at into v_prev_points,v_baseline_at
        from public.activity_history h where h.member_id=rec.id and h.recorded_at<=v_week_start
        order by h.recorded_at desc,h.id desc limit 1;
      select max(h.recorded_at) into v_latest_at from public.activity_history h
        where h.member_id=rec.id and h.recorded_at>v_week_start and h.recorded_at<=v_now;

      if v_baseline_at is null or v_baseline_at<v_week_start-interval '8 days' or v_latest_at is null then
        v_message:=format('%s weekly AP could not be verified because a recent baseline and an in-week snapshot are required. Upload a roster screenshot and keep periodic snapshots to enable reliable weekly checks.',
          left(replace(coalesce(rec.player_name,'Member'), '@', '@​'),100));
        insert into public.league_alerts(member_id,alert_type,period_start,fingerprint,title,message,severity)
        values(rec.id,'weekly_data_gap',v_week_start,
          'weekly_data_gap:'||rec.id::text||':'||to_char(v_week_start at time zone 'Asia/Kolkata','YYYY-MM-DD'),
          'Weekly AP needs more data',v_message,'info')
        on conflict(fingerprint) do nothing returning id into v_alert_id;
        if v_alert_id is not null then v_gap_count:=v_gap_count+1; v_alert_id:=null; end if;
      else
        for snap in select activity_points,recorded_at,id from public.activity_history
          where member_id=rec.id and recorded_at>v_baseline_at and recorded_at<=v_now
          order by recorded_at,id
        loop
          if snap.activity_points >= coalesce(v_prev_points,0) then
            v_week_points:=v_week_points+snap.activity_points-coalesce(v_prev_points,0);
          else
            v_week_points:=v_week_points+snap.activity_points;
          end if;
          v_prev_points:=snap.activity_points;
        end loop;

        if v_week_points<v_week_target then
          v_message:=format('%s is below the weekly target: estimated %s / %s AP for the week beginning %s. This estimate depends on the saved snapshots.',
            left(replace(coalesce(rec.player_name,'Member'), '@', '@​'),100),
            v_week_points,v_week_target,to_char(v_week_start at time zone 'Asia/Kolkata','DD Mon YYYY'));
          insert into public.league_alerts(member_id,alert_type,period_start,fingerprint,title,message,severity)
          values(rec.id,'weekly_shortfall',v_week_start,
            'weekly_shortfall:'||rec.id::text||':'||to_char(v_week_start at time zone 'Asia/Kolkata','YYYY-MM-DD'),
            'Weekly AP target missed',v_message,'warning')
          on conflict(fingerprint) do nothing returning id into v_alert_id;
          if v_alert_id is not null then v_weekly_count:=v_weekly_count+1; v_alert_id:=null; end if;
        end if;
      end if;
    end loop;
  end if;

  begin
    select decrypted_secret into v_webhook from vault.decrypted_secrets
      where name='discord_webhook_url' limit 1;
  exception when undefined_table or insufficient_privilege then v_webhook:=null;
  end;

  if v_webhook is not null and length(v_webhook)>20 then
    for rec in select a.id,a.title,a.message from public.league_alerts a
      where a.created_at>=v_now-interval '2 minutes' and a.read_at is null
      order by a.created_at desc limit 25
    loop
      v_payload:=jsonb_build_object('content',left('**FCP League Manager** - '||rec.title||E'\n'||rec.message,1900),
        'allowed_mentions',jsonb_build_object('parse',jsonb_build_array()));
      begin
        perform net.http_post(url:=v_webhook,body:=v_payload,
          headers:=jsonb_build_object('Content-Type','application/json'),timeout_milliseconds:=10000);
      exception when others then null;
      end;
    end loop;
  end if;

  return jsonb_build_object('checked_at',v_now,'onboarding_alerts_created',v_onboarding_count,
    'weekly_shortfalls_created',v_weekly_count,'weekly_data_gaps_created',v_gap_count,
    'weekly_check_window',case when extract(isodow from v_local)=7 and v_local::time>=time '20:00'
      then 'open' else 'Sunday 20:00 Asia/Kolkata' end,
    'discord_connected',v_webhook is not null);
end;
$$;

revoke all on function public.monitor_league_activity() from public,anon,authenticated;
grant execute on function public.monitor_league_activity() to service_role;

do $$
begin
  if exists(select 1 from cron.job where jobname='fcp-league-monitor') then
    perform cron.unschedule(jobid) from cron.job where jobname='fcp-league-monitor';
  end if;
end $$;

select cron.schedule('fcp-league-monitor','*/30 * * * *','select public.monitor_league_activity();');

-- Reviewed roster snapshots and auditable manual-action review queue.
create table if not exists public.league_roster_snapshots (
  id bigint generated by default as identity primary key,
  scanned_at timestamptz not null default now(),
  source text not null default 'reviewed_screenshot_ocr'
    check (source in ('reviewed_screenshot_ocr','manual_entry')),
  uploaded_by uuid references auth.users(id) on delete set null,
  detected_rows integer not null default 0 check (detected_rows >= 0),
  saved_rows integer not null default 0 check (saved_rows >= 0),
  skipped_rows integer not null default 0 check (skipped_rows >= 0),
  failed_rows integer not null default 0 check (failed_rows >= 0),
  status text not null default 'processing'
    check (status in ('processing','complete','partial','failed')),
  created_at timestamptz not null default now()
);

create table if not exists public.league_roster_snapshot_rows (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.league_roster_snapshots(id) on delete cascade,
  member_id bigint references public.league_members(id) on delete set null,
  player_name text not null,
  activity_points integer not null check (activity_points >= 0),
  ocr_confidence integer check (ocr_confidence between 0 and 100),
  outcome text not null check (outcome in ('created','updated','skipped','failed')),
  details text,
  created_at timestamptz not null default now()
);

create index if not exists league_roster_snapshots_scanned_at_idx
  on public.league_roster_snapshots(scanned_at desc);
create index if not exists league_roster_snapshot_rows_snapshot_idx
  on public.league_roster_snapshot_rows(snapshot_id, id);
create index if not exists league_roster_snapshot_rows_member_idx
  on public.league_roster_snapshot_rows(member_id, created_at desc);

create table if not exists public.league_action_reviews (
  id bigint generated by default as identity primary key,
  member_id bigint references public.league_members(id) on delete set null,
  source_alert_id bigint not null unique references public.league_alerts(id) on delete cascade,
  action_type text not null default 'manual_remove' check (action_type = 'manual_remove'),
  status text not null default 'pending' check (status in ('pending','approved','declined','completed')),
  reason text not null,
  proposed_at timestamptz not null default now(),
  proposed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  completed_at timestamptz,
  completed_by uuid references auth.users(id) on delete set null,
  completion_note text
);

create index if not exists league_action_reviews_status_idx
  on public.league_action_reviews(status, proposed_at desc);

alter table public.league_roster_snapshots enable row level security;
alter table public.league_roster_snapshot_rows enable row level security;
alter table public.league_action_reviews enable row level security;

drop policy if exists "League admins manage roster snapshots" on public.league_roster_snapshots;
create policy "League admins manage roster snapshots" on public.league_roster_snapshots
  for all to authenticated using (public.is_league_admin()) with check (public.is_league_admin());

drop policy if exists "League admins manage roster snapshot rows" on public.league_roster_snapshot_rows;
create policy "League admins manage roster snapshot rows" on public.league_roster_snapshot_rows
  for all to authenticated using (public.is_league_admin()) with check (public.is_league_admin());

drop policy if exists "League admins read action reviews" on public.league_action_reviews;
create policy "League admins read action reviews" on public.league_action_reviews
  for select to authenticated using (public.is_league_admin());

grant select, insert, update, delete on public.league_roster_snapshots, public.league_roster_snapshot_rows to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke insert, update, delete on public.league_action_reviews from anon, authenticated;
grant select on public.league_action_reviews to authenticated;

create or replace function public.create_action_review_for_shortfall()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.alert_type in ('onboarding_shortfall','weekly_shortfall') and new.member_id is not null then
    insert into public.league_action_reviews(member_id, source_alert_id, reason)
    values(new.member_id, new.id, new.message)
    on conflict (source_alert_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists league_shortfall_action_review on public.league_alerts;
create trigger league_shortfall_action_review
after insert on public.league_alerts
for each row execute function public.create_action_review_for_shortfall();

insert into public.league_action_reviews(member_id, source_alert_id, reason)
select a.member_id, a.id, a.message
from public.league_alerts a
where a.alert_type in ('onboarding_shortfall','weekly_shortfall')
  and a.member_id is not null
on conflict (source_alert_id) do nothing;

create or replace function public.review_league_action(p_action_id bigint, p_decision text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'league_admin', false) then
    raise exception 'League administrator role required';
  end if;
  if p_decision not in ('approve','decline') then
    raise exception 'Decision must be approve or decline';
  end if;
  update public.league_action_reviews
     set status = case when p_decision = 'approve' then 'approved' else 'declined' end,
         reviewed_at = now(),
         reviewed_by = auth.uid()
   where id = p_action_id and status = 'pending';
  if not found then
    raise exception 'Review item not found or no longer pending';
  end if;
end;
$$;

create or replace function public.complete_league_action(p_action_id bigint, p_note text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'league_admin', false) then
    raise exception 'League administrator role required';
  end if;
  if nullif(trim(coalesce(p_note,'')), '') is null then
    raise exception 'A completion note is required';
  end if;
  update public.league_action_reviews
     set status = 'completed',
         completed_at = now(),
         completed_by = auth.uid(),
         completion_note = left(trim(p_note),500)
   where id = p_action_id and status = 'approved';
  if not found then
    raise exception 'Action must be approved before it can be marked completed';
  end if;
end;
$$;

revoke all on function public.create_action_review_for_shortfall() from public, anon, authenticated;
revoke all on function public.review_league_action(bigint,text) from public, anon;
revoke all on function public.complete_league_action(bigint,text) from public, anon;
grant execute on function public.review_league_action(bigint,text) to authenticated;
grant execute on function public.complete_league_action(bigint,text) to authenticated;
